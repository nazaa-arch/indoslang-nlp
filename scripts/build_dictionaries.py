# Function to convert raw tuples to standardized entry format
def convert_to_entries(raw_dict, default_source, default_license):
    entries = {}
    for key, val in raw_dict.items():
        if isinstance(val, dict):
            entries[key] = val
        else:
            norm, cat, conf, amb = val
            # Skip identity mappings (word mapping to itself, e.g. saja -> saja)
            if key.strip().lower() == norm.strip().lower() and not amb:
                continue
            entries[key] = {
                "senses": [
                    {
                        "normalized": norm,
                        "category": cat,
                        "confidence": conf
                    }
                ],
                "ambiguous": amb,
                "source": default_source,
                "license": default_license
            }
    return entries

